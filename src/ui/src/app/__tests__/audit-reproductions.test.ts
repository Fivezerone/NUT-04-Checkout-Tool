/**
 * src/ui/src/app/__tests__/audit-reproductions.test.ts
 *
 * Appendix A Reproductions: Expected-Failing Tests for Audited Defects.
 * Each test reproduces a specific audited defect on the current pre-fix code.
 *
 * As each phase resolves its defects, its corresponding test is flipped from
 * `it.fails` to `it` (passing).
 *
 * Mappings:
 *   - A1: F-01 (Unresolved colour utilities) -> Phase 1
 *   - A2: F-06 (Token cascade & duplicate :root declarations) -> Phase 1
 *   - A3: F-02 (CAD MFA bypass & client-writable sessionStorage) -> Phase 2
 *   - A4: F-03 (Audit Trail false assurance on empty/unverified data) -> Phase 2
 *   - A5: F-04 (Fail-open grade fallbacks in sidepanel, shopper, callout, badge) -> Phase 3
 *   - A6: F-08 (In-page flyout Shadow DOM Tab trap & focus theft) -> Phase 3
 *   - A7: F-12 (3-calendar-month retention boundary & multi-store purge) -> Phase 6
 *   - A8: F-13 (REST client absolute URL & error propagation) -> Phase 2
 *   - A9: F-05 (Client-simulated link code & crypto-shredding flows) -> Phase 2
 */

import { describe, it, expect } from 'vitest'
import { readFileSync, existsSync, readdirSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { verifyAuditHashChain } from '../../cad/views/AuditLogView'
import { retentionCutoff, RETENTION_MONTHS } from '../lib/timeframes'
import { subMonths, startOfDay } from 'date-fns'

const ROOT = resolve(__dirname, '../../../../..')

describe('Appendix A: Pre-Fix Audit Reproductions', () => {
  // A1: Colour utilities (F-01) - CLOSED in Phase 1
  it('A1: built CSS generates rules for custom colour utilities', () => {
    const extAssets = resolve(ROOT, 'dist/extension/assets')
    const cssFiles = existsSync(extAssets)
      ? readdirSync(extAssets).filter((f) => f.endsWith('.css')).map((f) => join(extAssets, f))
      : []
    expect(cssFiles.length).toBeGreaterThan(0)
    const combinedCss = cssFiles.map((f) => readFileSync(f, 'utf8')).join('\n')

    // On post-fix code, .bg-surface, .text-strong, .border-border-control are generated by Tailwind v4
    expect(combinedCss).toMatch(/\.bg-surface\b/)
    expect(combinedCss).toMatch(/\.text-strong\b/)
    expect(combinedCss).toMatch(/\.border-control\b|\.border-border-control\b/)
  })

  // A2: Cascade (F-06) - CLOSED in Phase 1
  it('A2: no custom property is declared twice in :root with conflicting values and legacy tokens.css is removed', () => {
    const legacyPath = resolve(ROOT, 'src/ui/src/styles/tokens.css')
    expect(existsSync(legacyPath)).toBe(false)

    const themeCss = readFileSync(resolve(ROOT, 'src/ui/src/styles/theme.css'), 'utf8')
    // theme.css no longer sets --input: transparent
    expect(themeCss).not.toMatch(/--input:\s*transparent/)
  })

  // A3: MFA (F-02) - CLOSED in Phase 2
  it('A3: CAD MFA rejects arbitrary six-digit inputs and does not trust client sessionStorage', () => {
    const authContextSrc = readFileSync(resolve(ROOT, 'src/ui/src/cad/context/AuthContext.tsx'), 'utf8')

    // Post-fix code derives MFA strictly from server tokens without trusting sessionStorage
    expect(authContextSrc).not.toMatch(/sessionStorage\.setItem\(['"]cad_mfa_verified['"]/)
    expect(authContextSrc).not.toMatch(/^\s*setMfaVerified\(true\)/m)
    expect(authContextSrc).not.toMatch(/defaultClaims[\s\S]*role:\s*['"]patient['"]/)
  })

  // A4: Audit Trail (F-03) - CLOSED in Phase 2
  it('A4: audit log view never displays verified state without actual verified rows', () => {
    const auditViewSrc = readFileSync(resolve(ROOT, 'src/ui/src/cad/views/AuditLogView.tsx'), 'utf8')

    // Post-fix code uses tri-state verificationStatus and never assumes verified on 0 rows
    expect(auditViewSrc).not.toMatch(/useState<boolean>\(true\)/)
    expect(auditViewSrc).not.toMatch(/setChainValid\(true\)/)
  })

  // A5: Grades (F-04) - CLOSED in Phase 3
  it('A5: fail-closed grade rendering has zero fallbacks to C or B', () => {
    const shopperShellSrc = readFileSync(resolve(ROOT, 'src/ui/src/app/components/ShopperShell.tsx'), 'utf8')
    const sidepanelSrc = readFileSync(resolve(ROOT, 'src/ui/src/sidepanel.tsx'), 'utf8')
    const sharedUiSrc = readFileSync(resolve(ROOT, 'src/extension/adapters/shared-ui.js'), 'utf8')

    // Pre-fix fallbacks eliminated:
    expect(shopperShellSrc).not.toMatch(/gradeSnapshot\s*\|\|\s*['"]C['"]/)
    expect(sidepanelSrc).not.toMatch(/useState<['"][A-E]['"]>\(['"]C['"]\)/)
    expect(sharedUiSrc).not.toMatch(/averageGrade\s*\|\|\s*['"]B['"]/)
    expect(sharedUiSrc).not.toMatch(/gradeColors\.C/)
  })

  // A6: In-page flyout Tab trap (F-08) - CLOSED in Phase 3
  it('A6: flyout Tab trap uses shadow root activeElement, not document.activeElement', () => {
    const sharedUiSrc = readFileSync(resolve(ROOT, 'src/extension/adapters/shared-ui.js'), 'utf8')

    // Uses shadow root activeElement:
    expect(sharedUiSrc).toMatch(/flyoutEl\.getRootNode\(\)\.activeElement/)
    expect(sharedUiSrc).not.toMatch(/document\.activeElement === first/)
  })

  // A7: Retention boundary (F-12) - CLOSED in Phase 6
  it('A7: retention cutoff is calendar-month based (3 calendar months), not a fixed 90-day approximation', () => {
    const cartDbSrc = readFileSync(resolve(ROOT, 'src/ui/src/app/lib/db/cart.ts'), 'utf8')
    const backgroundSrc = readFileSync(resolve(ROOT, 'src/extension/background.js'), 'utf8')

    // Pre-fix code uses Date.now() - RETENTION_90_DAYS_MS or (90 * 24 * 60 * 60 * 1000)
    expect(cartDbSrc).not.toMatch(/RETENTION_90_DAYS_MS/)
    expect(backgroundSrc).not.toMatch(/90 \* 24 \* 60 \* 60 \* 1000/)
  })

  // A8: REST client (F-13) - CLOSED in Phase 2
  it('A8: PostgrestQueryBuilder uses absolute apiUrl from env and propagates errors on 5xx', () => {
    const storageSrc = readFileSync(resolve(ROOT, 'src/ui/src/services/storage.ts'), 'utf8')

    // Post-fix code defaults baseUrl using env.apiUrl and avoids relative '/rest/v1' fallback
    expect(storageSrc).not.toMatch(/constructor\(table:\s*string,\s*baseUrl\s*=\s*['"]\/rest\/v1['"]\)/)
  })

  // A9: Simulated flows (F-05) - CLOSED in Phase 2
  it('A9: CAD destructive and credential flows do not use Math.random client-side', () => {
    const consentViewSrc = readFileSync(resolve(ROOT, 'src/ui/src/cad/views/PatientLinkingConsentView.tsx'), 'utf8')
    const userMgmtSrc = readFileSync(resolve(ROOT, 'src/ui/src/cad/views/UserManagementView.tsx'), 'utf8')

    // Post-fix code uses real API endpoints without client-side Math.random() simulation
    expect(consentViewSrc).not.toMatch(/Math\.random\(\)/)
    expect(userMgmtSrc).not.toMatch(/Nutri\$\{Math\.floor/)
  })
})
